def landscape():
    w, h = 800, 450
    im = Image.new("RGB", (w, h))
    d = ImageDraw.Draw(im)
    for y in range(h):
        t = y / h
        d.line((0, y, w, y), fill=(int(9 + 15 * t), int(21 + 31 * t), int(34 + 30 * t)))
    for _ in range(230):
        x, y = rng.randrange(w), rng.randrange(235)
        c = rng.choice(("#496975", "#315360", "#223b4c", "#607682"))
        d.point((x, y), fill=c)

    for radius, color in [(52, "#1a3546"), (42, "#213e4b"), (33, "#8fada5"), (29, "#afc3ae")]:
        d.ellipse((651-radius, 79-radius, 651+radius, 79+radius), fill=color)
    for x, y, span in [(638, 67, 14), (654, 91, 13), (629, 82, 7), (665, 68, 5)]:
        d.line((x,y,x+span,y), fill="#9bb4a5", width=2)

    for baseline, color, colors, peaks in [
        (224, "#284152", ("#365665", "#59737a"), [(0,145),(85,119),(170,154),(276,85),(346,122),(429,98),(532,165),(607,107),(704,128),(800,66)]),
        (270, "#213b4c", ("#2a4959", "#496773"), [(0,184),(140,172),(250,126),(308,154),(340,200),(473,142),(560,164),(668,182),(751,122),(800,151)]),
        (322, "#1b3343", ("#214353", "#355867"), [(0,187),(74,217),(161,188),(254,258),(351,203),(452,242),(563,231),(661,209),(729,198),(800,211)]),
    ]:
        poly = [(0, baseline), *peaks, (800, baseline)]
        d.polygon(poly, fill=color)
        for i, (x, y) in enumerate(peaks[1:-1], 1):
            if y > peaks[i-1][1] or y > peaks[i+1][1]:
                continue
            rise = min(peaks[i-1][1] - y, peaks[i+1][1] - y)
            width = min(39, max(12, int(1.2*rise)))
            d.polygon([(x,y),(x-width,y+rise),(x-9,y+rise-2),(x-3,y+rise+10),(x+3,y+rise-4),(x+width,y+rise)],fill=colors[1])
            d.polygon([(x,y),(x+width,y+rise),(x+11,y+rise-5),(x+25,baseline),(x+1,y+rise)],fill=colors[0])

    d.polygon([(0,295),(157,281),(294,297),(460,284),(587,295),(800,274),(800,h),(0,h)], fill="#203d4c")
    for _ in range(880):
        x, y = rng.randrange(w), rng.randrange(295, h)
        d.line((x,y,x+rng.randrange(1,8),y),fill=rng.choice(("#294858","#254353","#365564","#203a4a")))

    for _ in range(106):
        x = rng.randrange(w)
        y = rng.randrange(239,326)
        ht = rng.randrange(6,29)
        wd = max(2, ht//5)
        d.line((x,y-ht,x,y+4),fill="#162c38",width=2)
        for z in range(3):
            cy = y-ht+z*ht//4
            sz = wd*(z+2)//3
            d.polygon([(x,cy),(x-sz,cy+ht//2),(x+sz,cy+ht//2)],fill="#193440")
            if z == 0:
                d.line((x-1,cy,x-sz,cy+ht//2),fill="#365762")
    for off, color in [(0,"#121f2a"),(8,"#4d6367"),(11,"#1f323a"),(19,"#576768")]:
        d.line((0,397+off, 800,288+off//3),fill=color,width=4)
    for x in range(0,800,15):
        y = 397 - x*109//800
        d.line((x,y-2,x+8,y+24-x//65),fill="#31494d",width=2)
    for x in (19, 112, 227, 433, 716, 779):
        y = 387 - x*105//800
        d.line((x,y-31,x,y+7), fill="#122631",width=3)
        d.rectangle((x-2,y-33,x+3,y-28),fill="#425358")
        if x in (112,433,716):
            d.point((x,y-31),fill="#f0ad63")
    for _ in range(390):
        x,y=rng.randrange(w),rng.randrange(h)
        d.point((x,y), fill=rng.choice(("#456771","#627f80","#507481","#354c5a")))
    im.resize((1600,900), Image.Resampling.NEAREST).save(ART / "landscape.png")


