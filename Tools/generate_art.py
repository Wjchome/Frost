def stamp(name, shapes, hostile=False):
    im = Image.new("RGBA", (96, 66))
    d = ImageDraw.Draw(im)
    glow = (179,105,79,16) if hostile else (98,195,192,20)
    for i in range(4):
        d.ellipse((21+i*4,7+i*3,74-i*4,62-i*3), fill=glow)
    for x,y in [(14,29),(25,11),(70,20),(76,42),(22,51),(61,8),(83,33),(33,7)]:
        d.line((x-1,y,x+2,y), fill=("#784944" if hostile else "#486d79"))
    d.ellipse((22,55,75,62),fill=(5,12,20,105))
    for color, points in shapes:
        d.polygon(points, fill=color)
    im.resize((192,132), Image.Resampling.NEAREST).save(ART / f"{name}.png")


